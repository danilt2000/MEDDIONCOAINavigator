import { writeFileSync } from 'node:fs';
import {
  DynamicColor,
  Hct,
  MaterialDynamicColors,
  SchemeTonalSpot,
  argbFromHex,
  hexFromArgb,
} from '@material/material-color-utilities';

export const SEED = '#2E6B8F';

export function tokensCss(seed) {
  const source = Hct.fromInt(argbFromHex(seed));
  const light = new SchemeTonalSpot(source, false, 0);
  const dark = new SchemeTonalSpot(source, true, 0);
  const roles = Object.values(MaterialDynamicColors).filter(
    (value) => value instanceof DynamicColor && !value.name.endsWith('palette_key_color'),
  );
  const declarations = roles.map((color) => {
    const token = color.name.replaceAll('_', '-');
    return `  --md-sys-color-${token}: light-dark(${hexFromArgb(color.getArgb(light))}, ${hexFromArgb(color.getArgb(dark))});`;
  });
  return `/* Generated by scripts/tokens.mjs from seed ${seed}. Run "pnpm --filter @navigator/ui tokens" after changing SEED. */
:root {
  color-scheme: light dark;
${declarations.join('\n')}
}
`;
}

if (process.argv[1] === import.meta.filename) {
  writeFileSync(new URL('../src/tokens.css', import.meta.url), tokensCss(SEED));
}
